export const COPY: Record<AppLang, Record<keyof typeof es, string>> = { es, en, pt };

export type CopyKey = keyof typeof es;

export function useT() {
  const lang = useLocale((s) => s.lang);
  return (key: CopyKey, vars?: Record<string, string | number>) => {
    let s = COPY[lang][key] || COPY.es[key];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    }
    return s;
  };
}

export function formatAgo(ts: number, t: (k: CopyKey, v?: Record<string, string | number>) => string) {
  if (!ts) return "";
  const s = Math.max(0, (Date.now() - ts) / 1000);
  if (s < 90) return t("now");
  if (s < 3600) return t("minAgo", { n: Math.floor(s / 60) });
  if (s < 86_400) return t("hAgo", { n: Math.floor(s / 3600) });
  const d = Math.floor(s / 86_400);
  return d === 1 ? t("d1Ago") : t("dAgo", { n: d });
}

